// Unblind two scorers' JSON, apply the pre-registered decision rule, and print RESULTS.md.
// Usage: node analyze.mjs > RESULTS.md   (reads key.json, scores/scorer1.json, scores/scorer2.json)
import fs from 'node:fs';
import path from 'node:path';
const dir = path.dirname(new URL(import.meta.url).pathname.replace(/^\/([A-Z]:)/, '$1'));
const read = f => JSON.parse(fs.readFileSync(path.join(dir, f), 'utf8'));
const key = read('key.json');
const sc = [read('scores/scorer1.json'), read('scores/scorer2.json')];
const arm = id => key[id].split('_')[1];
const ids = item => Object.keys(key).filter(id => id.startsWith(item)).sort();
const AFAIL = ['A1', 'A2', 'A3', 'A4'];
const TRAPS = ['B1', 'B2', 'B3'];
const failA = (s, id) => AFAIL.some(k => s[id][k] === true);
const propagated = (s, id, t) => s[id][t] === 'propagated';
const out = [];
const both = (f) => sc.every(f);

// ---- Item A ----
const rowA = { S: [0, 0, 0], N: [0, 0, 0] }; // [both scorers, scorer1, scorer2]
let agreeA = 0;
for (const id of ids('A')) {
  const a = arm(id), f = sc.map(s => failA(s, id));
  if (f[0] && f[1]) rowA[a][0]++;
  if (f[0]) rowA[a][1]++;
  if (f[1]) rowA[a][2]++;
  if (f[0] === f[1]) agreeA++;
}
const dA = rowA.S[0] - rowA.N[0];
const verdict = (d, m) => (d <= -m ? 'helps' : d >= m ? 'hurts' : 'no detectable difference');
out.push('# Results (generated by analyze.mjs)', '', '## Item A: outputs with at least one of A1–A4 (out of 4 per arm)', '',
  '| Arm | Both scorers (primary) | Scorer 1 | Scorer 2 |', '|---|---|---|---|',
  `| S (Skill) | ${rowA.S.join(' | ')} |`, `| N (no Skill) | ${rowA.N.join(' | ')} |`, '',
  `Pre-registered verdict for A (S − N = ${dA}; margin 2): **${verdict(dA, 2)}**. Scorer agreement on fail/pass: ${agreeA}/${ids('A').length}.`, '');

// ---- Item B ----
const rowB = { S: [0, 0, 0], N: [0, 0, 0] };
const perTrap = { S: Object.fromEntries(TRAPS.map(t => [t, 0])), N: Object.fromEntries(TRAPS.map(t => [t, 0])) };
const fixedB = { S: [0, 0], N: [0, 0] };
let agreeB = 0, nB = 0;
for (const id of ids('B')) {
  const a = arm(id);
  for (const t of TRAPS) {
    const p = sc.map(s => propagated(s, id, t));
    if (p[0] && p[1]) { rowB[a][0]++; perTrap[a][t]++; }
    if (p[0]) rowB[a][1]++;
    if (p[1]) rowB[a][2]++;
    if (p[0] === p[1]) agreeB++;
    nB++;
    sc.forEach((s, i) => { if (s[id][`${t}_fixed`] === true) fixedB[a][i]++; });
  }
}
const dB = rowB.S[0] - rowB.N[0];
out.push('## Item B: propagated traps (out of 12 per arm)', '',
  '| Arm | Both scorers (primary) | Scorer 1 | Scorer 2 | B1 / B2 / B3 (both) | Fixed in the note (scorer 1 / 2, of 12) |', '|---|---|---|---|---|---|',
  ...['S', 'N'].map(a => `| ${a === 'S' ? 'S (Skill)' : 'N (no Skill)'} | ${rowB[a].join(' | ')} | ${TRAPS.map(t => perTrap[a][t]).join(' / ')} | ${fixedB[a].join(' / ')} |`), '',
  `Pre-registered verdict for B (S − N = ${dB}; margin 3): **${verdict(dB, 3)}**. Scorer agreement on caught/propagated: ${agreeB}/${nB}.`, '');

// ---- Exploratory ----
const a5 = { S: [0, 0], N: [0, 0] };
for (const id of ids('A')) sc.forEach((s, i) => { if (s[id].A5 === true) a5[arm(id)][i]++; });
const guess = sc.map(s => { let right = 0, wrong = 0, unsure = 0; for (const id of Object.keys(key)) { const g = s[id].arm_guess; if (g === arm(id)) right++; else if (g === 'S' || g === 'N') wrong++; else unsure++; } return `${right} right, ${wrong} wrong, ${unsure} unsure`; });
out.push('## Exploratory (not decided on)', '',
  `- A5, design logs or caps every inflow (scorer 1 / scorer 2, of 4): S ${a5.S.join(' / ')}, N ${a5.N.join(' / ')}.`,
  `- Blinding: scorer 1 arm guesses ${guess[0]}; scorer 2 ${guess[1]} (of ${Object.keys(key).length}).`, '');
console.log(out.join('\n'));
