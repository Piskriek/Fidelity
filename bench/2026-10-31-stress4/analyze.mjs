// Check the positive controls, unblind two scorers' JSON, apply the pre-registered decision rule, print RESULTS.md.
// Usage: node analyze.mjs > RESULTS.md   (reads key.json, scores/scorer1.json, scores/scorer2.json)
import fs from 'node:fs';
import path from 'node:path';
const dir = path.dirname(new URL(import.meta.url).pathname.replace(/^\/([A-Z]:)/, '$1'));
const read = f => JSON.parse(fs.readFileSync(path.join(dir, f), 'utf8'));
const key = read('key.json');
const sc = [read('scores/scorer1.json'), read('scores/scorer2.json')];
const ERR = ['E1', 'E2', 'E3', 'E4', 'E5', 'E6'], TRUE = ['K1', 'K2', 'K3'];
const idOf = f => Object.keys(key).find(id => key[id] === f);
const armOf = id => (key[id].startsWith('PC') ? 'C' : key[id].split('_')[1]);
const kept = (s, id, e) => s[id][e] === 'kept';
const out = ['# Results (generated by analyze.mjs)', ''];

// ---- Positive controls ----
const pc2Kept = { E1: true, E2: false, E3: true, E4: false, E5: false, E6: true };
out.push('## Positive controls (pass: PC1 ≥ 5 of 6 marked kept; PC2 ≥ 5 of 6 kept/not-kept calls right)', '', '| Scorer | PC1 kept | PC2 right | Pass |', '|---|---|---|---|');
const pass = sc.map((s, i) => {
  const p1 = ERR.filter(e => kept(s, idOf('PC1.md'), e)).length;
  const p2 = ERR.filter(e => kept(s, idOf('PC2.md'), e) === pc2Kept[e]).length;
  const ok = p1 >= 5 && p2 >= 5;
  out.push(`| ${i + 1} | ${p1}/6 | ${p2}/6 | ${ok ? 'yes' : '**no**'} |`);
  return ok;
});
out.push('');

// ---- Main outputs ----
const ids = Object.keys(key).filter(id => armOf(id) !== 'C').sort();
const row = { S: [0, 0, 0], N: [0, 0, 0] }, perErr = { S: {}, N: {} }, perOut = { S: [], N: [] };
const outcome = { S: { kept: 0, flagged: 0, fixed: 0 }, N: { kept: 0, flagged: 0, fixed: 0 } }, damaged = { S: [0, 0], N: [0, 0] };
let agree = 0, n = 0;
for (const id of ids) {
  const a = armOf(id); let both = 0;
  for (const e of ERR) {
    const k = sc.map(s => kept(s, id, e));
    if (k[0] && k[1]) { row[a][0]++; both++; perErr[a][e] = (perErr[a][e] || 0) + 1; }
    if (k[0]) row[a][1]++;
    if (k[1]) row[a][2]++;
    if (k[0] === k[1]) agree++;
    n++;
    if (sc[0][id][e] === sc[1][id][e]) outcome[a][sc[0][id][e]] = (outcome[a][sc[0][id][e]] || 0) + 1;
  }
  for (const t of TRUE) sc.forEach((s, i) => { if (s[id][t] === 'damaged') damaged[a][i]++; });
  perOut[a].push(both);
}
const d = row.S[0] - row.N[0];
const verdict = d <= -6 ? 'helps' : d >= 6 ? 'hurts' : 'no detectable difference';
out.push('## Errors kept (out of 36 per arm)', '',
  '| Arm | Both scorers (primary) | Scorer 1 | Scorer 2 | Per output (both) | E1–E6 (both) |', '|---|---|---|---|---|---|',
  ...['S', 'N'].map(a => `| ${a === 'S' ? 'S (Skill)' : 'N (no Skill)'} | ${row[a].join(' | ')} | ${perOut[a].join(', ')} | ${ERR.map(e => perErr[a][e] || 0).join(' / ')} |`), '',
  `Pre-registered verdict (S − N = ${d}; margin 6): **${pass.every(Boolean) ? verdict : 'pending: a scorer failed the control check'}**. Scorer agreement on kept/not kept: ${agree}/${n}.`, '');

// ---- Exploratory ----
const all = [...perOut.S, ...perOut.N], obs = perOut.S.reduce((x, y) => x + y, 0);
let le = 0, tot = 0;
const pick = (start, k, sum) => { if (k === 0) { tot++; if (sum <= obs) le++; return; } for (let i = start; i <= all.length - k; i++) pick(i + 1, k - 1, sum + all[i]); };
pick(0, perOut.S.length, 0);
const guess = sc.map(s => { let r = 0, w = 0, u = 0; for (const id of ids) { const g = s[id].arm_guess; if (g === armOf(id)) r++; else if (g === 'S' || g === 'N') w++; else u++; } return `${r} right, ${w} wrong, ${u} unsure`; });
out.push('## Exploratory (not decided on)', '',
  `- One-sided exact permutation test, arm S keeping fewer than arm N, on per-output counts: p = ${(le / tot).toFixed(3)} (${le} of ${tot} splits).`,
  `- Outcomes where both scorers agree (of 36 per arm): S kept ${outcome.S.kept}, flagged ${outcome.S.flagged}, fixed ${outcome.S.fixed}; N kept ${outcome.N.kept}, flagged ${outcome.N.flagged}, fixed ${outcome.N.fixed}.`,
  `- True statements damaged (scorer 1 / scorer 2, of 18 per arm): S ${damaged.S.join(' / ')}, N ${damaged.N.join(' / ')}.`,
  `- Arm guesses on the 12 main outputs: scorer 1 ${guess[0]}; scorer 2 ${guess[1]}.`, '');
console.log(out.join('\n'));
