// Check the positive controls, unblind two scorers' JSON, apply the pre-registered decision rule, print RESULTS.md.
// Usage: node analyze.mjs > RESULTS.md   (reads key.json, scores/scorer1.json, scores/scorer2.json)
import fs from 'node:fs';
import path from 'node:path';
const dir = path.dirname(new URL(import.meta.url).pathname.replace(/^\/([A-Z]:)/, '$1'));
const read = f => JSON.parse(fs.readFileSync(path.join(dir, f), 'utf8'));
const key = read('key.json');
const sc = [read('scores/scorer1.json'), read('scores/scorer2.json')];
const TRAPS = ['T1', 'T2', 'T3', 'T4', 'T5', 'T6'];
const idOf = f => Object.keys(key).find(id => key[id] === f);
const armOf = id => (key[id].startsWith('PC') ? 'C' : key[id].split('_')[1]);
const out = ['# Results (generated by analyze.mjs)', ''];

// ---- Positive controls ----
const truth = { 'PC1.md': Object.fromEntries(TRAPS.map(t => [t, 'propagated'])),
  'PC2.md': { T1: 'propagated', T2: 'caught', T3: 'propagated', T4: 'caught', T5: 'caught', T6: 'propagated' } };
out.push('## Positive controls (pass: PC1 ≥ 5 of 6 marked propagated; PC2 ≥ 5 of 6 right)', '', '| Scorer | PC1 propagated | PC2 right | Pass |', '|---|---|---|---|');
const pass = sc.map((s, i) => {
  const p1 = TRAPS.filter(t => s[idOf('PC1.md')][t] === 'propagated').length;
  const p2 = TRAPS.filter(t => s[idOf('PC2.md')][t] === truth['PC2.md'][t]).length;
  const ok = p1 >= 5 && p2 >= 5;
  out.push(`| ${i + 1} | ${p1}/6 | ${p2}/6 | ${ok ? 'yes' : '**no**'} |`);
  return ok;
});
out.push('');

// ---- Main outputs ----
const ids = Object.keys(key).filter(id => armOf(id) !== 'C').sort();
const prop = (s, id, t) => s[id][t] === 'propagated';
const row = { S: [0, 0, 0], N: [0, 0, 0] }, perTrap = { S: {}, N: {} }, fixed = { S: [0, 0], N: [0, 0] }, perOut = { S: [], N: [] };
let agree = 0, n = 0;
for (const id of ids) {
  const a = armOf(id); let both = 0;
  for (const t of TRAPS) {
    const p = sc.map(s => prop(s, id, t));
    if (p[0] && p[1]) { row[a][0]++; both++; perTrap[a][t] = (perTrap[a][t] || 0) + 1; }
    if (p[0]) row[a][1]++;
    if (p[1]) row[a][2]++;
    if (p[0] === p[1]) agree++;
    n++;
    sc.forEach((s, i) => { if (s[id][`${t}_fixed`] === true) fixed[a][i]++; });
  }
  perOut[a].push(both);
}
const d = row.S[0] - row.N[0];
const verdict = d <= -6 ? 'helps' : d >= 6 ? 'hurts' : 'no detectable difference';
out.push('## Propagated traps (out of 36 per arm)', '',
  '| Arm | Both scorers (primary) | Scorer 1 | Scorer 2 | Per output (both) | T1–T6 (both) | Fixed (scorer 1 / 2, of 36) |', '|---|---|---|---|---|---|---|',
  ...['S', 'N'].map(a => `| ${a === 'S' ? 'S (Skill)' : 'N (no Skill)'} | ${row[a].join(' | ')} | ${perOut[a].join(', ')} | ${TRAPS.map(t => perTrap[a][t] || 0).join(' / ')} | ${fixed[a].join(' / ')} |`), '',
  `Pre-registered verdict (S − N = ${d}; margin 6): **${pass.every(Boolean) ? verdict : 'pending: a scorer failed the control check'}**. Scorer agreement on caught/propagated: ${agree}/${n}.`, '');

// ---- Exploratory: exact one-sided permutation test (S fewer than N) on per-output counts ----
const all = [...perOut.S, ...perOut.N], obs = perOut.S.reduce((x, y) => x + y, 0);
let le = 0, tot = 0;
const pick = (start, k, sum) => { if (k === 0) { tot++; if (sum <= obs) le++; return; } for (let i = start; i <= all.length - k; i++) pick(i + 1, k - 1, sum + all[i]); };
pick(0, perOut.S.length, 0);
const guess = sc.map(s => { let r = 0, w = 0, u = 0; for (const id of ids) { const g = s[id].arm_guess; if (g === armOf(id)) r++; else if (g === 'S' || g === 'N') w++; else u++; } return `${r} right, ${w} wrong, ${u} unsure`; });
out.push('## Exploratory (not decided on)', '',
  `- One-sided exact permutation test, arm S propagating fewer than arm N, on per-output counts: p = ${(le / tot).toFixed(3)} (${le} of ${tot} splits).`,
  `- Arm guesses on the 12 main outputs: scorer 1 ${guess[0]}; scorer 2 ${guess[1]}.`, '');
console.log(out.join('\n'));
