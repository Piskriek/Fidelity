// Builds mind/live_thought.mjs from the locked v1a runner mind/live_v1a.mjs (its hash is checked first): the same runner, plus a
// read-only thought record (PLAN_FRACTAL.md, Track A step 2, Tier 1). With --thoughts <file> it writes one JSON line per tick:
// for each character, what it sensed, how expected that was, its guess spread and value for each choice, whether it explored,
// what it did, what came back, how sure it had been of that, and its sting after the answer. A separate "world" block holds
// what the world knows and the being does not (exact E and H, season, this kind's class, intensity, loop-breaks, the engine's
// gain and pain). Every value is read after the runner computed it; nothing written here feeds back, so a life with and without
// --thoughts must have the same chain, NGE and series (checked in RUNLOG_bridge.txt). Only the tick driver (liveMain) is patched.
//   node mind/make_thought.mjs [out]      (default mind/live_thought.mjs)
//   node mind/live_thought.mjs --live --arm L --trunk mind/runs/nursery/W0_s1.json --seed 1 --worlds 31000,1 --thoughts t.jsonl [--from 0 --to 2048]
import fs from 'node:fs';
import path from 'node:path';
import crypto from 'node:crypto';
import { fileURLToPath } from 'node:url';
const here = path.dirname(fileURLToPath(import.meta.url));
const SRC = path.join(here, 'live_v1a.mjs'), DST = process.argv[2] || path.join(here, 'live_thought.mjs');
const V1A = '7f814cbf959b6e9c885c28b0340b565abf15462f33c643f22532e1dcce9a20bc';
let s = fs.readFileSync(SRC, 'utf8');
const got = crypto.createHash('sha256').update(s).digest('hex');
if (got !== V1A) throw new Error(`live_v1a.mjs is ${got}, expected ${V1A}`);
const rep = (a, b) => { const n = s.split(a).length - 1; if (n !== 1) throw new Error(`expected 1 match, got ${n}: ${a.slice(0, 70)}`); s = s.replace(a, () => b); };
const NL = String.fromCharCode(10);

// 1. header
rep(`// live.mjs: the characters' fast loop (BRIDGE_DESIGN.md §4.6), generated by mind/make_live.mjs from nursery.mjs (afaa90a8…).`,
`// live_thought.mjs: live_v1a.mjs (${V1A.slice(0, 8)}…) plus a read-only thought record (--thoughts), generated by mind/make_thought.mjs.` + NL +
`// live.mjs: the characters' fast loop (BRIDGE_DESIGN.md §4.6), generated by mind/make_live.mjs from nursery.mjs (afaa90a8…).`);

// 2. the recorder's state, per run
rep(`  let k5 = 0, explored = 0, decisions = 0;`,
`  let k5 = 0, explored = 0, decisions = 0;
  const TH = args.thoughts ? { from: +(args.from || 0), to: +(args.to || ticks) } : null; // thought record: a tick window`);

// 3. per life: the rows, and the world's pre-step view (snapshot is a pure read; the observation is built from it as before)
rep(`    let lastSeason = -1, seasonStart = 0;`,
`    let lastSeason = -1, seasonStart = 0;
    const thRows = [];`);
rep(`      const obs = snapshot(w).valleys.map(b => K.encodeObs(b));`,
`      const snap0 = snapshot(w).valleys, obs = snap0.map(b => K.encodeObs(b));`);

// 4. after the OBS forward: how expected the observation was, and what the character expected (read before ACTION overwrites it)
rep(`      runStep(net, streams, buf, 1, { poison }); // OBS`,
`      runStep(net, streams, buf, 1, { poison }); // OBS
      const thObs = TH && t >= TH.from && t < TH.to ? streams.map((st, c) => { let best = K.OBS0, bp = -1; for (let i = K.OBS0; i <= T.DOWN; i++) if (st.pMain[i] > bp) { bp = st.pMain[i]; best = i; } return { pSeen: +st.pMain[obs[c]].toFixed(5), expected: best === T.DOWN ? { down: true } : K.decodeObs(best), pExpected: +bp.toFixed(5) }; }) : null; // thought record (read-only)`);

// 5. after the real ANSWER forward and K5, before any head step: the thought row for this tick (read-only)
rep(`      if (train) { streams.forEach(st => adamHeads(st, streams.length)); for (const k of Object.keys(net.P)) net.P[k].g.fill(0); }`,
`      if (thObs) { // thought record (read-only): every value below was already computed this tick; nothing here feeds back
        const snap1 = snapshot(w).valleys, tab = log.tables[log.tables.length - 1], cls = e => (e === NOURISH ? 'NOURISH' : e === TOXIC ? 'TOXIC' : 'PLAIN');
        thRows.push(JSON.stringify({ t, season: w.s, sinceTurn: t - seasonStart, chars: streams.map((st, c) => {
          const d0 = K.decodeObs(obs[c]), u1 = hash32(worldSeed, modelSeed, LIVE.exploreTag, ARM.stream, c, t) / 4294967296, ans = K.decodeAnswer(ansTok[c]);
          const guess = [EAT, PASS, REST].map(x => { const p = pi[x][c]; let z = 0, u = 0; const q = []; for (let i = 0; i < nAns; i++) { z += p[T.ANS0 + i]; u += p[T.ANS0 + i] * wants[i]; q.push(+p[T.ANS0 + i].toFixed(5)); } return { p: q, off: +(1 - z).toFixed(6), value: +(u / z).toFixed(4) }; });
          return { sees: d0, ...thObs[c], guess, explore: u1 < LIVE.eps, act: ['EAT', 'PASS', 'REST'][acts[c]], answer: ans.name, starving: ans.starving, pAnswer: +st.pMain[ansTok[c]].toFixed(5), sting: st.sting.map(x => +x.toFixed(5)),
            world: { E: snap0[c].E, H: snap0[c].H, item: snap0[c].item, kindClass: !d0.down && d0.item ? cls(tab[c][d0.item - 1]) : null, ellAfter: snap1[c].ell, loopBreaksAfter: snap1[c].loopBreaks, gain: outs[c].gain, pain: outs[c].pain, V: outs[c].V, cause: outs[c].cause ?? null } };
        }) }));
      }
      if (train) { streams.forEach(st => adamHeads(st, streams.length)); for (const k of Object.keys(net.P)) net.P[k].g.fill(0); }`);

// 6. per life: write the thought file (a header line, then one line per tick in the window)
rep(`    console.log(JSON.stringify({ arm: armName, seed: modelSeed, worldSeed, NGE: +r.NGE.toFixed(2),`,
`    if (TH) {
      const file = nw === 1 ? args.thoughts : args.thoughts.replace(/(\\.jsonl)?$/, \`_w\${worldSeed}.jsonl\`);
      const answers = [...Array(nAns).keys()].map(i => { const a = K.decodeAnswer(T.ANS0 + i); return \`\${a.name}\${a.starving ? '/1' : ''}\`; });
      const head = { thoughts: 'tier1', arm: armName, seed: modelSeed, worldSeed, ticks, from: TH.from, to: Math.min(TH.to, ticks), script: selfHash, trunk: args.trunk, answers, wants: [...wants], chain: w.chain,
        note: 'sees/pSeen/expected/guess/explore/act/answer/pAnswer/sting are the being\\'s own; world holds what the world knows and the being does not. wants are the choice weights (gain minus pain at intensity 2), not felt.' };
      fs.writeFileSync(file, [JSON.stringify(head), ...thRows].join('\\n') + '\\n');
    }
    console.log(JSON.stringify({ arm: armName, seed: modelSeed, worldSeed, NGE: +r.NGE.toFixed(2),`);

fs.writeFileSync(DST, s);
console.log(`wrote ${DST} (${crypto.createHash('sha256').update(s).digest('hex').slice(0, 8)}) from live_v1a.mjs ${V1A.slice(0, 8)}`);
